# DINOv3 backbone + Feature Pyramid
#
# 职责分层（H4/H5 重构后的清晰语义）：
#   - OUT_INDICES（cfg.MODEL.DINOv3.OUT_INDICES）：用于控制 DINOv3Backbone/wrapper 取哪些 transformer 层。
#     空 → 取最后一层；非空 → 取指定层。与 FPN 无关。
#   - FEATURE_STRATEGY（cfg.MODEL.DINOv3.FEATURE_STRATEGY）：用于构造 FPN。
#     与取层无关，但会校验 OUT_INDICES 产出的 bottom_up 是否满足该 FPN 的输入需求，不满足直接报错。
#
# 三种 FPN 构造策略：
#   - "simple"     （ViTDet 风格）：单输入 → SimpleFeaturePyramid 用 ConvTranspose2d 上/下采样出 P2-P5。
#                   要求 bottom_up 只输出 1 个 feature。
#   - "multilayer" （DEIMv2 STA 风格，无融合）：多输入 → MultilayerFPN 每层各自 双线性插值/MaxPool 到目标 stride，层间不融合。
#                   固定输出 4 尺度 P2-P5；特征数 < 4 时自动复用最后一个。
#                   允许 bottom_up 输出任意 ≥1 个 feature。
#   - "full_token" （阶段三预留）：保留 CLS/register，进阶注入检测头。目前与 simple 同路径。
# ------------------------------------------------------------------


@BACKBONE_REGISTRY.register()
def build_dinov3_fpn_backbone(cfg, input_shape: ShapeSpec):
    """构建 DINOv3 ViT + 特征金字塔。

    流程：先调用 build_dinov3_backbone 得到 bottom_up（DINOv3Backbone），
    再根据 FEATURE_STRATEGY 在其上构造 FPN，并校验 bottom_up 输出是否符合该 FPN 需求。

    字段：
        cfg.MODEL.DINOv3.WEIGHTS/OUT_INDICES/FREEZE  传给 build_dinov3_backbone（决定取层与冻结）
        cfg.MODEL.DINOv3.FEATURE_STRATEGY            决定 FPN 构造方式（见上方注释）
        cfg.MODEL.FPN.OUT_CHANNELS/NORM              FPN 参数

    Returns:
        backbone (Backbone): simple 策略下输出 P2..P5。
    """
    strategy = cfg.MODEL.DINOv3.FEATURE_STRATEGY
    out_channels = cfg.MODEL.FPN.OUT_CHANNELS

    # OUT_INDICES 由 build_dinov3_backbone 内部处理（空→最后一层，非空→指定层）。
    bottom_up = build_dinov3_backbone(cfg, input_shape)
    n_out = len(bottom_up._out_features)  # bottom_up 实际输出的 feature 数

    # 根据 FEATURE_STRATEGY 构造 FPN，并校验 bottom_up 输出
    if strategy == "simple" or strategy == "full_token":
        # SimpleFeaturePyramid：单输入 → 上/下采样出 P2/P3/P4/P5
        if n_out != 1:
            raise ValueError(
                f'FEATURE_STRATEGY="{strategy}" 要求 DINOv3Backbone 只输出 1 个 feature，'
                f"实际 {n_out} 个（{bottom_up._out_features}）。"
                f"请调整 OUT_INDICES 使其只取 1 层（如 OUT_INDICES: [] 取最后一层，或 [12]）。"
            )
        in_feature = bottom_up._out_features[0]   # "dinov3_stage0"
        backbone = SimpleFeaturePyramid(
            net=bottom_up,
            in_feature=in_feature,
            out_channels=out_channels,
            scale_factors=[4.0, 2.0, 1.0, 0.5],   # stride16 → P2(4)/P3(8)/P4(16)/P5(32)
            norm=cfg.MODEL.FPN.NORM,              # LN
            top_block=None,                       # scale_factors 已含 0.5 产出 P5，无需额外 top block
        )
        return backbone
    elif strategy == "multilayer":
        # MultilayerFPN：多输入（或单输入）→ 每层各自插值/池化到目标 stride，无融合。
        # 固定输出 4 尺度 P2/P3/P4/P5；特征数 < 4 时自动复用最后一个（见 MultilayerFPN docstring）。
        if n_out == 1:
            # 柔性提示：multilayer 但只取了 1 层，所有尺度将复用该层（仍可运行）。
            print(
                f'[MultilayerFPN] 提示：OUT_INDICES 只产出 {n_out} 个特征（{bottom_up._out_features}），'
                "4 个尺度将全部复用该层。若需多层，请在 OUT_INDICES 指定多层（如 [8, 10, 12, 12]）。"
            )
        in_features = bottom_up._out_features   # ["dinov3_stage0", ...]
        backbone = MultilayerFPN(
            net=bottom_up,
            out_feature_names=in_features,
            out_channels=out_channels,
            norm=cfg.MODEL.FPN.NORM,
        )
        return backbone
    else:
        raise ValueError(f"未知的 MODEL.DINOv3.FEATURE_STRATEGY: {strategy}")
